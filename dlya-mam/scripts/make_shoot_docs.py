def card_lines(prefix, cards, extra=(), note=""):
    lines = []
    for num, q, types in list(cards) + list(extra):
        lines.append(f"- [ ] **{prefix}-{num}** — {q}  \n  ↳ {', '.join(R[t] for t in types)}")
    if note:
        lines.append(f"\n> {note}")
    return lines


def topic(prefix, title, cards, extra=(), note="", why=""):
    head = f"### {prefix} · {title}"
    if why:
        head += f"\n_{why}_"
    return [head, ""] + card_lines(prefix, cards, extra, note) + [""]


