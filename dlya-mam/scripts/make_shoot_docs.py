def faq_cards(n=40):
    rows = list(csv.DictReader(open(ROOT / "zamery" / "z18-faq-candidates.csv", encoding="utf-8")))
    bad = re.compile(r"взросл|препарат|лекарств|таблет|мазь|сироп|антибиот|дозиров|чем лечить|чем мазать|форум|код|мкб|что это$|это$", re.I)
    seen, out = {}, []
    for r in rows:
        q = r["related_query_as_card"].strip()
        if bad.search(q):
            continue
        k = r["source_query"]
        if seen.get(k, 0) >= 2:
            continue
        seen[k] = seen.get(k, 0) + 1
        out.append((f"{len(out) + 1:02d}", f"«{q[0].upper() + q[1:]}?» — ответьте, как маме, которая это ищет.", ["faq", "reels"]))
        if len(out) >= n:
            break
    return out


